export const useOrderStore = create((set, get) => ({
  orders: initialOrders,

  // Dashboard count helpers
  getTotalOrdersCount: () => get().orders.length,
  getInProductionCount: () => get().orders.filter((o) => o.status === 'IN_PRODUCTION').length,
  getPendingCount: () => get().orders.filter((o) => o.status === 'PENDING').length,
  getCompletedCount: () => get().orders.filter((o) => o.status === 'COMPLETED').length,

  getOrderById: (orderId) => {
    return get().orders.find((o) => o.id === orderId || o.orderNumber === orderId);
  },

  createOrder: (newOrderData) => {
    const nextNum = get().orders.length + 25;
    const orderNumber = `ORD-${nextNum}`;
    const newOrder = {
      id: orderNumber,
      orderNumber,
      producedMeters: 0,
      status: 'PENDING',
      stage: 'Pending Planning',
      assignedMachineId: null,
      assignedMachineName: 'Unassigned',
      assignedWorkerId: null,
      assignedWorkerName: 'Unassigned',
      unitPrice: Number(newOrderData.unitPrice) || 200,
      totalValue: (Number(newOrderData.quantityMeters) || 1000) * (Number(newOrderData.unitPrice) || 200),
      yarnReservedKg: 0,
      notes: newOrderData.notes || 'Order created via Everest ERP portal',
      ...newOrderData,
      quantityMeters: Number(newOrderData.quantityMeters) || 1000,
    };

    set((state) => ({
      orders: [newOrder, ...state.orders],
    }));

    return newOrder;
  },

  updateOrderStatus: (orderId, status, stage) => {
    set((state) => ({
      orders: state.orders.map((o) => {
        if (o.id === orderId || o.orderNumber === orderId) {
          return {
            ...o,
            status,
            stage: stage || o.stage,
          };
        }
        return o;
      }),
    }));
  },

  updateProductionProgress: (orderId, producedMeters) => {
    set((state) => ({
      orders: state.orders.map((o) => {
        if (o.id === orderId || o.orderNumber === orderId) {
          const qty = Number(o.quantityMeters);
          const newProduced = Math.min(qty, Number(producedMeters));
          const isDone = newProduced >= qty;
          return {
            ...o,
            producedMeters: newProduced,
            status: isDone ? 'COMPLETED' : o.status,
            stage: isDone ? 'Quality Check Passed' : o.stage,
          };
        }
        return o;
      }),
    }));
  },

  assignOrderToMachine: (orderId, machineId, machineName, workerId, workerName) => {
    set((state) => ({
      orders: state.orders.map((o) => {
        if (o.id === orderId || o.orderNumber === orderId) {
          return {
            ...o,
            status: 'IN_PRODUCTION',
            stage: 'Weaving',
            assignedMachineId: machineId,
            assignedMachineName: machineName,
            assignedWorkerId: workerId,
            assignedWorkerName: workerName,
          };
        }
        return o;
      }),
    }));
  },
}));
